#!/usr/bin/env python3
"""Боковой канал для украинского/белорусского — отдельно от основного языка.

Основной язык (русский) не смешивается с боковым: `norm_words` остаётся
[a-zа-яё], индекс RAG не перестраивается. Боковые слова существуют отдельно и
приводятся к русской форме только на стороне запроса, чтобы запрос на мове мог
попасть в существующий русский индекс.

Роль бокового языка — сигнал, а не язык корпуса: включение украинского слова в
русскую речь — признак токсичности и враждебности (правило пользователя), поэтому
боковой канал не участвует в scoring корпуса как язык и не влияет на то, как
индексируются документы. Если весь текст на мове (не вставка), доля боковых слов
это показывает, и текст обрабатывается как обычно — по своему языку.
"""
import re

SIDE_MAP = {"і": "и", "ї": "и", "є": "е", "ґ": "г", "ў": "у"}
# Класс был {3,} — тогда правила END_MAP («ця», «їх», «ій») были недостижимы:
# слово из 2 букв никогда не попадало в side_words, и морфология молча не применялась.
SIDE_CLASS = r"[a-zа-яёіїєґў]{2,}"
# Порог, обещанный docstring («≥ порога — язык текста»). 0.6: при 0.5 фрагмент
# «Копам він» (1 боковое слово из 2) решал язык, хотя правило навыка говорит, что
# короткий фрагмент язык не решает.
SIDE_THRESHOLD = 0.6
# Окончания: буквы дают только графику, морфология остаётся чужой — 'манипуляцыя'
# не совпадёт с русской 'манипуляция'. Правила применяются к уже приведённому слову.
END_MAP = [("цыя", "ция"), ("ця", "ца"), ("їх", "их"), ("ій", "ий")]


def to_ru(word):
    # Сначала окончания (они читаются в исходной форме), потом графика.
    for src, dst in END_MAP:
        if word.endswith(src):
            word = word[:-len(src)] + dst
            break
    return "".join(SIDE_MAP[c] if c in SIDE_MAP else c for c in word)


def side_words(text):
    """Слова с боковыми буквами, приведённые к русской форме.

    Возвращает (русские_формы, число_боковых_слов, всего_слов) — доля нужна, чтобы
    отличить вставку от языка всего текста (язык вставки решает доля, а не число).
    """
    words = re.findall(SIDE_CLASS, text.lower())
    side = [w for w in words if any(c in SIDE_MAP for c in w)]
    return [to_ru(w) for w in side], len(side), len(words)


def side_share(text):
    """Доля боковых слов: ≥ SIDE_THRESHOLD — язык текста, меньше — вставка."""
    _, side, total = side_words(text)
    return (side / total) if total else 0.0


def is_side_language(text):
    """Вердикт по доле: True — текст сам на мове, False — боковое слово как вставка."""
    return side_share(text) >= SIDE_THRESHOLD
